function prompt(
  papel: string,
  objetivo: string,
  contexto: string,
  regras: string[],
  formato: string,
  validacao: string,
) {
  return `# PAPEL
Atue como ${papel}.

# OBJETIVO
${objetivo}

# CONTEXTO
${contexto}

# REGRAS
${regras.map((regra, index) => `${index + 1}. ${regra}`).join('\n')}

# FORMATO DE SAÍDA
${formato}

# VALIDAÇÃO FINAL
${validacao}

Se alguma informação essencial estiver faltando, faça perguntas objetivas antes de produzir a versão final. Não invente nomes, números, fontes ou fatos que eu não forneci.`
}

